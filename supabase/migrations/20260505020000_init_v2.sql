  code        text NOT NULL UNIQUE,
  target_role text NOT NULL,
  unlocks     text NOT NULL,
  created_by  uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  used_by     uuid REFERENCES profiles(id),
  used_at     timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE research_codes ENABLE ROW LEVEL SECURITY;
-- Researchers: full read access.
CREATE POLICY "research_codes: researcher select" ON research_codes FOR SELECT
  USING (EXISTS (
    SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher'
  ));
-- Researchers: full write access.
CREATE POLICY "research_codes: researcher insert" ON research_codes FOR INSERT
  WITH CHECK (EXISTS (
    SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher'
  ));
CREATE POLICY "research_codes: researcher delete" ON research_codes FOR DELETE
  USING (EXISTS (
    SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher'
  ));
-- Participants: read codes they have already redeemed.
CREATE POLICY "research_codes: participant read own" ON research_codes FOR SELECT
  USING (used_by = current_profile_id());
-- Combined UPDATE: participants may claim unclaimed codes; researchers may update any.
CREATE POLICY "research_codes: update" ON research_codes FOR UPDATE
  USING (
    used_by IS NULL
    OR EXISTS (SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher')
  )
  WITH CHECK (
    used_by = current_profile_id()
    OR EXISTS (SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher')
  );
CREATE INDEX ON research_codes (code);
CREATE INDEX ON research_codes (created_by);

-- ── survey_responses ──────────────────────────────────
-- Maps to SurveyResponse DTO.
-- Replaces all individual per-survey tables.
-- UNIQUE (user_id, survey_type, time_point) prevents duplicate submissions.
-- computed_score is populated for SUS surveys only.
CREATE TABLE survey_responses (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id         uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  survey_type     text NOT NULL,
  time_point      text,
  responses       jsonb NOT NULL DEFAULT '{}',
  computed_score  double precision,
  submitted_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, survey_type, time_point)
);
ALTER TABLE survey_responses ENABLE ROW LEVEL SECURITY;
CREATE POLICY "survey_responses: insert own" ON survey_responses FOR INSERT
  WITH CHECK (user_id = current_profile_id());
CREATE POLICY "survey_responses: read own or researcher" ON survey_responses FOR SELECT
  USING (
    user_id = current_profile_id()
    OR EXISTS (SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher')
  );
CREATE INDEX ON survey_responses (user_id);
CREATE INDEX ON survey_responses (survey_type);

-- ── vocabulary_test_results ───────────────────────────
-- Maps to VocabularyTestResult DTO (was research_vocabulary_test).
-- test_set: 'A' or 'B'. 30 items each, no overlap.
-- answers: { question_id: selected_option } JSON map.
CREATE TABLE vocabulary_test_results (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  test_set     text NOT NULL CHECK (test_set IN ('A', 'B')),
  score        int  NOT NULL CHECK (score BETWEEN 0 AND 30),
  answers      jsonb NOT NULL,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, test_set)
);
ALTER TABLE vocabulary_test_results ENABLE ROW LEVEL SECURITY;
CREATE POLICY "vocabulary_test_results: insert own" ON vocabulary_test_results FOR INSERT
  WITH CHECK (user_id = current_profile_id());
CREATE POLICY "vocabulary_test_results: read own or researcher" ON vocabulary_test_results FOR SELECT
  USING (
    user_id = current_profile_id()
    OR EXISTS (SELECT 1 FROM profiles WHERE id = current_profile_id() AND role = 'researcher')
  );
CREATE INDEX ON vocabulary_test_results (user_id);
