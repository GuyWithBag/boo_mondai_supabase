-- ── profiles ──────────────────────────────────────────
-- id        = local app UUID (generated by client or backend)
-- user_id   = FK to auth.users (always non-null; backend creates the row)
-- No email column — email lives in auth.users only.
-- No updated_at — not in the Profile DTO.
CREATE TABLE profiles (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id         uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  username        text NOT NULL,
  role            text NOT NULL DEFAULT 'group_a_participant'
                  CHECK (role IN ('group_a_participant', 'group_b_participant', 'researcher')),
  avatar_url      text,
  target_language text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
-- Everyone can read profiles (leaderboard, attribution, etc.)
CREATE POLICY "profiles: read all" ON profiles FOR SELECT USING (true);
-- Users may only update their own profile row.
CREATE POLICY "profiles: update own" ON profiles FOR UPDATE
  USING     ((select auth.uid()) = user_id)
  WITH CHECK ((select auth.uid()) = user_id);
-- INSERT is handled by the backend via service role — no user-level insert policy.
CREATE INDEX ON profiles (user_id);

-- ── Helper: resolve auth.uid() → profiles.id ─────────
-- Used throughout RLS policies. SECURITY DEFINER so it can always read profiles
-- even when called from within an RLS expression.
CREATE OR REPLACE FUNCTION current_profile_id()
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id FROM profiles WHERE user_id = (select auth.uid()) LIMIT 1
$$;

