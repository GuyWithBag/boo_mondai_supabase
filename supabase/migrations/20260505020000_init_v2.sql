-- ── card_templates ────────────────────────────────────
-- Wide table: all subclass-specific fields are nullable columns.
-- The `type` discriminator tells dart_mappable which subclass to use.
--
-- Column ownership by subclass:
--
--   flashcard:          front_text, back_text,
--                       front_image_url, back_image_url,
--                       front_audio_url, back_audio_url,
--                       card_type
--
--   identification:     prompt_text, accepted_answers,
--                       image_url, audio_url
--
--   multiple_choice:    question_prompt,
--                       image_url, audio_url
--
--   word_scramble:      sentence_to_scramble,
--                       image_url, audio_url
--
--   fill_in_the_blanks: (content in fill_in_the_blank_segments table)
--   match_madness:      (content in match_madness_pairs table)
CREATE TABLE card_templates (
  -- ── base CardTemplate fields ──────────────────
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  deck_id              uuid NOT NULL REFERENCES decks(id) ON DELETE CASCADE,
  type                 text NOT NULL
                       CHECK (type IN (
                         'flashcard', 'identification', 'multiple_choice',
                         'fill_in_the_blanks', 'word_scramble', 'match_madness'
                       )),
  sort_order           int  NOT NULL DEFAULT 0,
  source_template_id   uuid REFERENCES card_templates(id) ON DELETE SET NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),

  -- ── FlashcardTemplate ─────────────────────────
  front_text           text,
  back_text            text,
  front_image_url      text,
  back_image_url       text,
  front_audio_url      text,
  back_audio_url       text,
  card_type            card_type,      -- normal | reversed | both

  -- ── IdentificationTemplate ────────────────────
  prompt_text          text,
  accepted_answers     text,           -- comma-separated accepted answers

  -- ── MultipleChoiceTemplate ────────────────────
  question_prompt      text,

  -- ── WordScrambleTemplate ──────────────────────
  sentence_to_scramble text,

  -- ── Shared: identification, multiple_choice, word_scramble ──
  image_url            text,
  audio_url            text
);
